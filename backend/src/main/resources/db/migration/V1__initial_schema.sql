CREATE TABLE hackathons (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name varchar(120) NOT NULL, description varchar(4000) NOT NULL,
 start_date timestamp with time zone NOT NULL, end_date timestamp with time zone NOT NULL,
 submission_deadline timestamp with time zone NOT NULL, status varchar(30) NOT NULL,
 scoring_strategy varchar(30) NOT NULL, created_at timestamp with time zone NOT NULL,
 CHECK(start_date < end_date), CHECK(submission_deadline >= start_date AND submission_deadline <= end_date)
);
CREATE TABLE teams (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name varchar(100) NOT NULL, name_key varchar(100) NOT NULL, description varchar(2000) NOT NULL,
 technology_stack varchar(500) NOT NULL, status varchar(30) NOT NULL,
 hackathon_id bigint NOT NULL REFERENCES hackathons(id), created_at timestamp with time zone NOT NULL,
 UNIQUE(hackathon_id, name_key)
);
CREATE TABLE participants (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, full_name varchar(100) NOT NULL,
 email varchar(254) NOT NULL, email_key varchar(254) NOT NULL, role varchar(80) NOT NULL,
 team_id bigint NOT NULL REFERENCES teams(id), UNIQUE(team_id,email_key)
);
CREATE TABLE hackathon_tasks (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title varchar(160) NOT NULL,
 description varchar(3000) NOT NULL, task_type varchar(31) NOT NULL,
 deadline timestamp with time zone NOT NULL, hackathon_id bigint NOT NULL REFERENCES hackathons(id),
 duration_minutes integer, question_count integer
);
CREATE TABLE evaluation_criteria (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(100) NOT NULL,
 description varchar(1000) NOT NULL, weight double precision NOT NULL CHECK(weight>0 AND weight<=1),
 max_score double precision NOT NULL CHECK(max_score>0), hackathon_id bigint NOT NULL REFERENCES hackathons(id)
);
CREATE TABLE submissions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title varchar(160) NOT NULL,
 description varchar(5000) NOT NULL, repository_url varchar(1000) NOT NULL,
 presentation_url varchar(1000), demo_url varchar(1000),
 team_id bigint NOT NULL REFERENCES teams(id), task_id bigint REFERENCES hackathon_tasks(id),
 submitted_at timestamp with time zone NOT NULL, status varchar(30) NOT NULL,
 late_penalty boolean NOT NULL DEFAULT false, early_bonus boolean NOT NULL DEFAULT false,
 originality_bonus boolean NOT NULL DEFAULT false, CHECK(NOT (late_penalty AND early_bonus))
);
CREATE TABLE evaluations (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 submission_id bigint NOT NULL REFERENCES submissions(id), judge_name varchar(100) NOT NULL,
 judge_key varchar(100) NOT NULL, comment varchar(3000) NOT NULL, evaluated_at timestamp with time zone NOT NULL,
 UNIQUE(submission_id,judge_key)
);
CREATE TABLE evaluation_scores (
 evaluation_id bigint NOT NULL REFERENCES evaluations(id), criterion_id bigint NOT NULL REFERENCES evaluation_criteria(id),
 score double precision NOT NULL CHECK(score>=0), PRIMARY KEY(evaluation_id,criterion_id)
);
CREATE TABLE notifications (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, event_type varchar(80) NOT NULL,
 message varchar(500) NOT NULL, hackathon_id bigint NOT NULL REFERENCES hackathons(id),
 created_at timestamp with time zone NOT NULL, is_read boolean NOT NULL DEFAULT false
);
CREATE TABLE audit_logs (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, event_type varchar(80) NOT NULL,
 message varchar(500) NOT NULL, hackathon_id bigint NOT NULL REFERENCES hackathons(id), created_at timestamp with time zone NOT NULL
);
CREATE INDEX submissions_team_idx ON submissions(team_id);
CREATE INDEX evaluations_submission_idx ON evaluations(submission_id);
CREATE INDEX teams_hackathon_idx ON teams(hackathon_id);
CREATE INDEX notification_time_idx ON notifications(created_at);
